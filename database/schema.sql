-- ---------------------------------------------------------------------
-- 1. SCHEMAS
--    staging : data as extracted from office files, before validation
--    dw      : validated data in a star schema, used for reporting
--    audit   : what the pipeline did (files, runs, data-quality issues)
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS audit;

COMMENT ON SCHEMA staging IS 'Landing zone: office submissions as extracted, before validation';
COMMENT ON SCHEMA dw      IS 'Data warehouse: validated data in a star schema for reporting';
COMMENT ON SCHEMA audit   IS 'Pipeline audit trail: file registry, run log, data-quality issues';

-- ---------------------------------------------------------------------
-- 2. DIMENSION TABLES (dw)
--    Each dimension has:
--      * a SURROGATE key (..._key): a meaningless integer generated by the
--        database, used for joins from fact tables
--      * the NATURAL key from the source (e.g. 'DEP05'), kept UNIQUE
--    CHECK constraints are the last line of defence: even if the pipeline
--    had a bug, the database would refuse invalid values.
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS dw.dim_department (
    department_key       SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    department_id        VARCHAR(10)  NOT NULL UNIQUE
                         CHECK (department_id ~ '^DEP[0-9]{2}$'),
    department_name      VARCHAR(100) NOT NULL UNIQUE,
    department_category  VARCHAR(50)  NOT NULL,
    directorate          VARCHAR(100) NOT NULL,
    loaded_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON TABLE dw.dim_department IS 'One row per department (15). Grain: department.';

CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_key   SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    office_id      VARCHAR(10)  NOT NULL UNIQUE
                   CHECK (office_id ~ '^OFF[0-9]{2}$'),
    office_name    VARCHAR(100) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    country        VARCHAR(100) NOT NULL,
    region         VARCHAR(100) NOT NULL,
    office_type    VARCHAR(50)  NOT NULL,
    loaded_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON TABLE dw.dim_location IS 'One row per office / duty station (10). Grain: office.';

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key       INTEGER  PRIMARY KEY,            -- e.g. 20250314 (readable, sortable)
    full_date      DATE     NOT NULL UNIQUE,
    year           SMALLINT NOT NULL,
    quarter        SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month          SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name     VARCHAR(10) NOT NULL,
    year_month     CHAR(7)  NOT NULL,                -- '2025-03'
    month_start    DATE     NOT NULL,
    day_of_week    SMALLINT NOT NULL,                -- 1 = Monday ... 7 = Sunday
    is_month_end   BOOLEAN  NOT NULL
);
COMMENT ON TABLE dw.dim_date IS 'Calendar table, one row per day. Populated by database/seed_data.sql.';

CREATE TABLE IF NOT EXISTS dw.dim_employee (
    employee_key            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id             VARCHAR(10)  NOT NULL UNIQUE
                            CHECK (employee_id ~ '^E[0-9]{5}$'),
    first_name              VARCHAR(100) NOT NULL,
    last_name               VARCHAR(100) NOT NULL,
    gender                  VARCHAR(30)  NOT NULL
                            CHECK (gender IN ('Female', 'Male', 'Non-binary / Not disclosed')),
    date_of_birth           DATE,
    nationality             VARCHAR(100),
    employment_type         VARCHAR(20)  NOT NULL
                            CHECK (employment_type IN ('Fixed-term', 'Continuing', 'Temporary', 'Consultant', 'Intern')),
    grade_level             VARCHAR(10)  NOT NULL
                            CHECK (grade_level IN ('G3','G4','G5','G6','G7','P1','P2','P3','P4','P5','D1','D2','Non-staff')),
    job_title               VARCHAR(150),
    current_department_key  SMALLINT REFERENCES dw.dim_department (department_key),
    current_location_key    SMALLINT NOT NULL REFERENCES dw.dim_location (location_key),
    supervisor_id           VARCHAR(10)
                            REFERENCES dw.dim_employee (employee_id) DEFERRABLE INITIALLY DEFERRED,
    hire_date               DATE NOT NULL,
    contract_start_date     DATE,
    contract_end_date       DATE,
    employment_status       VARCHAR(20)  NOT NULL CHECK (employment_status IN ('Active', 'Separated')),
    exit_date               DATE,
    last_updated            DATE,
    loaded_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Business rules enforced by the database itself
    CHECK (supervisor_id IS NULL OR supervisor_id <> employee_id),
    CHECK (contract_end_date IS NULL OR contract_start_date IS NULL OR contract_end_date >= contract_start_date),
    CHECK (date_of_birth IS NULL OR date_of_birth < hire_date),
    CHECK (exit_date IS NULL OR exit_date >= hire_date),
    CHECK ((employment_status = 'Separated') = (exit_date IS NOT NULL))
);
COMMENT ON TABLE dw.dim_employee IS 'One row per employee, CURRENT state (Type 1). History lives in fact_workforce_snapshot.';

CREATE INDEX IF NOT EXISTS ix_dim_employee_department ON dw.dim_employee (current_department_key);
CREATE INDEX IF NOT EXISTS ix_dim_employee_location   ON dw.dim_employee (current_location_key);
CREATE INDEX IF NOT EXISTS ix_dim_employee_supervisor ON dw.dim_employee (supervisor_id);
